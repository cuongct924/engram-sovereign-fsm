#!/usr/bin/env python3
"""Regenerates the ablation modules from the CURRENT base modules, so they cannot drift from the spec.

Each ablation is the base module with one mechanism removed by a single textual edit that must match exactly once:

  EngramFSM_Ablation_NoHysteresis       drops `safe_blocks = RECOVERY_HYSTERESIS_WAIT` from the RECOVERING -> ANCHORED branch
  EngramFSM_Ablation_NoP2PGate          drops the IsP2PQualityHealthy conjunct of IsHealthyCondition
  EngramFSM_Ablation_NoDABackfill       drops `da_backfill_valid = TRUE` from the RECOVERING -> ANCHORED branch
  EngramTendermint_Ablation_NoCircuitBreaker   drops the withdrawal-lock conjunct of IsValidProposal
  EngramTendermint_Ablation_NoDAConsistency    drops `prop.da_receipt.attestation = TRUE` of IsValidProposal
  EngramServer_Ablation_NoCircuitBreaker / _NoDAConsistency   EngramServer with EXTENDS pointing at the ablated Tendermint module

(EngramTendermint_Ablation_NoFastForward and its Server copy are not generated: that ablation has no reliable result.)

    python3 spec/tools/make_ablations.py
"""

import os
import re
import sys

CORE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core")
STAMP = "\\* GENERATED by spec/tools/make_ablations.py from {base}.tla -- do not edit by hand; rerun the script.\n"


def read(name):
    with open(os.path.join(CORE, name + ".tla")) as f:
        return f.read()


def write(name, text):
    with open(os.path.join(CORE, name + ".tla"), "w") as f:
        f.write(text)


def rename(text, base, new):
    out, n = re.subn(rf"MODULE {base}\b", f"MODULE {new}", text, count=1)
    assert n == 1, f"{base}: module header not found"
    # the module line is the first line; the generated-stamp goes right after it
    first, rest = out.split("\n", 1)
    return first + "\n" + STAMP.format(base=base) + rest


def drop_line(text, stripped):
    lines = text.split("\n")
    hits = [i for i, l in enumerate(lines) if l.strip() == stripped]
    assert len(hits) == 1, f"expected one line `{stripped}`, found {len(hits)}"
    del lines[hits[0]]
    return "\n".join(lines)


def replace_once(text, old, new):
    assert text.count(old) == 1, f"expected one `{old}`, found {text.count(old)}"
    return text.replace(old, new, 1)


def main():
    fsm = read("EngramFSM")
    write("EngramFSM_Ablation_NoHysteresis", rename(replace_once(
        fsm, "/\\ safe_blocks = RECOVERY_HYSTERESIS_WAIT /\\ reanchoring_proof_valid = TRUE",
        "/\\ reanchoring_proof_valid = TRUE"), "EngramFSM", "EngramFSM_Ablation_NoHysteresis"))
    write("EngramFSM_Ablation_NoP2PGate", rename(drop_line(fsm, "/\\ IsP2PQualityHealthy"),
                                                 "EngramFSM", "EngramFSM_Ablation_NoP2PGate"))
    write("EngramFSM_Ablation_NoDABackfill", rename(replace_once(
        fsm, '/\\ da_backfill_valid = TRUE -> "ANCHORED"', '-> "ANCHORED"'), "EngramFSM", "EngramFSM_Ablation_NoDABackfill"))

    tm = read("EngramTendermint")
    cb = rename(drop_line(tm, '/\\ (prop.fsm_state \\in {"SOVEREIGN", "RECOVERING"}) => ~ContainsWithdrawal(prop.value)'),
                "EngramTendermint", "EngramTendermint_Ablation_NoCircuitBreaker")
    da = rename(drop_line(tm, "/\\ prop.da_receipt.attestation = TRUE"),
                "EngramTendermint", "EngramTendermint_Ablation_NoDAConsistency")
    write("EngramTendermint_Ablation_NoCircuitBreaker", cb)
    write("EngramTendermint_Ablation_NoDAConsistency", da)

    sv = read("EngramServer")
    for tag in ("NoCircuitBreaker", "NoDAConsistency"):
        text = replace_once(sv, "EngramFSM, EngramTendermint\n", f"EngramFSM, EngramTendermint_Ablation_{tag}\n")
        write(f"EngramServer_Ablation_{tag}", rename(text, "EngramServer", f"EngramServer_Ablation_{tag}"))
    print("regenerated 7 ablation modules")


if __name__ == "__main__":
    sys.exit(main())
