#!/usr/bin/env python3
"""Writes the two Apalache variants that the inductive refinement-step check (MC_ServerRefinementStep_Apalache) needs.

Apalache rejects RECURSIVE operators, and EngramConsensus.tla defines SumStakeOp recursively; anything that INSTANCEs it
(EngramServerRefinement.tla) therefore cannot be checked as it is. This script derives, from the CURRENT base modules:

  EngramConsensus_Apalache.tla          SumStakeOp rewritten with ApaFoldSet (same value, no recursion); EXTENDS Apalache added
  EngramServerRefinement_Apalache.tla   the refinement module, INSTANCEing EngramConsensus_Apalache

so they cannot drift from the spec (same idea as make_ablations.py). The base modules are not touched.

    python3 spec/tools/make_apalache_refinement.py
"""

import os
import re

CORE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core")
STAMP = "\\* GENERATED by spec/tools/make_apalache_refinement.py from {base}.tla -- do not edit by hand; rerun the script.\n"


def read(name):
    with open(os.path.join(CORE, name + ".tla")) as f:
        return f.read()


def write(name, text):
    with open(os.path.join(CORE, name + ".tla"), "w") as f:
        f.write(text)


def replace_once(text, old, new):
    assert text.count(old) == 1, f"expected one `{old}`, found {text.count(old)}"
    return text.replace(old, new, 1)


def rename(text, base, new):
    out, n = re.subn(rf"MODULE {base}\b", f"MODULE {new}", text, count=1)
    assert n == 1, f"{base}: module header not found"
    first, rest = out.split("\n", 1)
    return first + "\n" + STAMP.format(base=base) + rest


def main():
    cons = read("EngramConsensus")
    cons = replace_once(cons, "EXTENDS Naturals, FiniteSets\n", "EXTENDS Naturals, FiniteSets, Apalache\n")
    cons = replace_once(
        cons,
        "RECURSIVE SumStakeOp(_)\n"
        "\\* @type: (Set(Str)) => Int;\n"
        "SumStakeOp(Q) == IF Q = {} THEN 0 ELSE LET n == CHOOSE x \\in Q : TRUE IN Stake[n] + SumStakeOp(Q \\ {n})\n",
        "\\* @type: (Int, Str) => Int;\n"
        "AddStake(acc, n) == acc + Stake[n]\n"
        "\\* @type: (Set(Str)) => Int;\n"
        "SumStakeOp(Q) == ApaFoldSet(AddStake, 0, Q)\n",
    )
    write("EngramConsensus_Apalache", rename(cons, "EngramConsensus", "EngramConsensus_Apalache"))

    ref = read("EngramServerRefinement")
    ref, n = re.subn(r"(?m)^(\s+)INSTANCE EngramConsensus WITH", r"\g<1>INSTANCE EngramConsensus_Apalache WITH", ref)
    assert n == 1, f"expected one INSTANCE line, found {n}"
    write("EngramServerRefinement_Apalache", rename(ref, "EngramServerRefinement", "EngramServerRefinement_Apalache"))
    print("wrote EngramConsensus_Apalache.tla and EngramServerRefinement_Apalache.tla")


if __name__ == "__main__":
    main()
