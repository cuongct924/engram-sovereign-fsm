#!/usr/bin/env python3
"""Turns a Terraform stack's `inventory` output into deploy/ansible/inventory/hosts.yml.

Usage:
    deploy/bin/make-inventory.py deploy/terraform/aws
    terraform -chdir=deploy/terraform/aws output -json inventory | deploy/bin/make-inventory.py -

Hand-written inventories (any provider, bare metal) skip this script: see
deploy/ansible/inventory/example.yml. Stdlib only.
"""

import json
import os
import subprocess
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ansible", "inventory", "hosts.yml")


def load(arg: str) -> dict:
    if arg == "-":
        return json.load(sys.stdin)
    out = subprocess.run(["terraform", f"-chdir={arg}", "output", "-json", "inventory"],
                         check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def render(inv: dict) -> str:
    validators = sorted(inv["validators"], key=lambda v: v["index"])
    if sorted(v["index"] for v in validators) != list(range(1, len(validators) + 1)):
        raise SystemExit("validator indexes must be 1..N with no gaps")
    lines = [
        "# Generated by deploy/bin/make-inventory.py; regenerate after every terraform apply.",
        "all:",
        "  vars:",
        f"    ansible_user: {inv['ssh_user']}",
        "  children:",
        "    infra:",
        "      hosts:",
        f"        {inv['infra']['name']}:",
        f"          ansible_host: {inv['infra']['ip']}",
        f"          region: {inv['infra']['region']}",
    ]
    if inv.get("prover"):
        lines += [
            "    prover:",
            "      hosts:",
            f"        {inv['prover']['name']}:",
            f"          ansible_host: {inv['prover']['ip']}",
            f"          region: {inv['prover']['region']}",
        ]
    lines += [
        "    validators:",
        "      hosts:",
    ]
    for v in validators:
        lines += [
            f"        {v['name']}:",
            f"          ansible_host: {v['ip']}",
            f"          node_index: {v['index']}",
            f"          region: {v['region']}",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    text = render(load(sys.argv[1]))
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
