package keeper

import (
	"os"
	"testing"

	"github.com/stretchr/testify/require"

	"cosmossdk.io/collections/colltest"
)

// VerifyZKProof must fail closed: garbage proof/public-input bytes are always
// rejected (never accepted, never panic) -- a malformed or corrupted proof
// rejects rather than silently accepting.
func TestVerifyZKProof_FailsClosedOnGarbage(t *testing.T) {
	storeService, _ := colltest.MockStore()
	k := NewKeeper(storeService, nil)

	require.False(t, k.VerifyZKProof([]byte("not a real proof"), []byte("not real inputs")))
	require.False(t, k.VerifyZKProof(nil, nil))
	require.False(t, k.VerifyZKProof(make([]byte, 1024), make([]byte, 1024)))
}

// VerifyZKProof must accept a real proof generated by the pinned `bb prove`
// (5.0.0-nightly.20260522, matching Dockerfile's BB_VERSION) against
// embeddedVK, and reject the same proof with a single byte flipped --
// cross-validating the embedded wasm32-wasi verifier (zk_verifier_wasm.go)
// against the real circuit/reanchoring toolchain rather than a synthetic
// fixture. Regenerate zk_assets/testdata/* via `bb prove`/`bb write_vk`
// (see circuit/reanchoring/README.md) whenever the circuit or embeddedVK
// changes -- a stale fixture here would mask exactly the prover/verifier
// version-skew failure mode this verifier was built to catch (see
// https://github.com/cuongct924/engram-barretenberg-wasm's README).
func TestVerifyZKProof_RealProof(t *testing.T) {
	storeService, _ := colltest.MockStore()
	k := NewKeeper(storeService, nil)

	proofValid, err := os.ReadFile("zk_assets/testdata/proof_valid")
	require.NoError(t, err)
	proofTampered, err := os.ReadFile("zk_assets/testdata/proof_tampered")
	require.NoError(t, err)
	inputsValid, err := os.ReadFile("zk_assets/testdata/inputs_valid")
	require.NoError(t, err)

	require.True(t, k.VerifyZKProof(proofValid, inputsValid), "real proof against embeddedVK must verify")
	require.False(t, k.VerifyZKProof(proofTampered, inputsValid), "tampered proof must be rejected")
}
