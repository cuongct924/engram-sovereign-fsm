#!/usr/bin/env python3
"""E11 -> docs/paper/results/rq2_table.tex (the RQ2 comparison table of the paper).

One row per (fault, system), cells mean (min--max) over trials, same metrics and windows as
summarize_e11.py. Rows for a system with no trials yet are left out.

    python3 scripts/e11_hard_gated_baseline/make_latex_table.py
"""

import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, ".."))
import summarize_e11 as s  # noqa: E402 (importing it does not run main; matplotlib must be installed)

OUT = os.path.join(HERE, "..", "..", "docs", "paper", "results", "rq2_table.tex")
SYSTEM = {"hard-gated": "Receipt-gated, vote-extension receipts", "hard-gated-oob": "Receipt-gated, direct-read receipts", "engram": "Engram", "soft": "Soft"}
FAULT = {"btc": "Checkpoint pause", "da": "DA outage", "both": "Both"}


def cell(values, nd=0):
    vals = [v for v in values if v is not None]
    if not vals:
        return "---"
    mean = sum(vals) / len(vals)
    lo, hi = min(vals), max(vals)
    if round(lo, nd) == round(hi, nd):
        return f"{mean:.{nd}f}"
    return f"{mean:.{nd}f} ({lo:.{nd}f}--{hi:.{nd}f})"


def main() -> int:
    rows = s.load_rows()
    lock = s.lock_times(rows)
    groups = defaultdict(list)
    for r in rows:
        groups[(r["fault"], r["mode"])].append(r)
    out = []
    for fault in s.FAULTS:
        first = True
        for mode in s.MODES:
            g = groups.get((fault, mode))
            if not g:
                continue
            ratio = [s.num(r["fault_blocks_per_s"]) / s.num(r["baseline_blocks_per_s"]) * 100 for r in g]
            around = [s.withdrawals_around_lock(r, lock[fault]) for r in g] if fault in lock else []
            stalled = sum(1 for r in g if r["stalled"] == "True")
            label = f"\\multirow{{{sum(1 for m in s.MODES if groups.get((fault, m)))}}}{{*}}{{{FAULT[fault]}}}" if first else ""
            first = False
            out.append(" & ".join([
                label, SYSTEM[mode], str(len(g)),
                cell([s.num(r["fault_blocks"]) for r in g]), cell(ratio) + "\\%",
                cell([s.num(r["longest_gap_s"]) for r in g], 1), cell([s.num(r["max_round_in_fault"]) for r in g]),
                f"{stalled}/{len(g)}",
                cell([a for _, a in around]) if around else "---", cell([b for b, _ in around]) if around else "---",
            ]) + " \\\\")
        out.append("\\midrule")
    if out and out[-1] == "\\midrule":
        out.pop()
    lock_txt = ", ".join(f"{FAULT[f].lower()} {lock[f]:.0f}\\,s" for f in s.FAULTS if f in lock)
    body = "\n".join(out)
    tex = f"""% Generated by scripts/e11_hard_gated_baseline/make_latex_table.py -- do not edit.
\\begin{{tabular}}{{@{{}}llrrrrrrrr@{{}}}}
\\toprule
 & & & \\multicolumn{{2}}{{c}}{{Liveness in the fault}} & & & & \\multicolumn{{2}}{{c}}{{Withdrawals committed}} \\\\
\\cmidrule(lr){{4-5}}\\cmidrule(lr){{9-10}}
\\textbf{{Fault}} & \\textbf{{System}} & $n$ & Blocks & Rate & Longest gap (s) & Max round & No resume & After lock & Before lock \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
% lock times used for the two withdrawal columns: {lock_txt}
"""
    with open(OUT, "w") as f:
        f.write(tex)
    print(f"wrote {os.path.abspath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
