#!/usr/bin/env python3
"""Summarise the live three-phase runs of live_nonstationary.py (results_live/nonstationary_<config>_o<offset>_t<trial>_*.json).

One row per configuration and offset (seconds the chain stayed healthy in ANCHORED before the DA outage); three trials
each, so cells give the mean and the range (min--max), not an interval. Runs whose JSON is under a directory starting
with `_` (quarantined) are ignored.

    python3 scripts/e5_hysteresis_flapping/summarize_live_nonstationary.py
"""

import glob
import json
import os
import re
import statistics as st
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "results_live")
OUT = os.path.join(SRC, "nonstationary_summary.md")
TEX = os.path.join(HERE, "..", "..", "docs", "paper", "results", "nonstationary_live_table.tex")
ORDER = ["static2", "static4", "adaptiveW16", "adaptiveW64", "adaptiveW128", "adaptiveK4W64"]
FIELDS = [("noisy_flaps", "flaps", 1), ("noisy_demotions", "demotions", 1), ("noisy_anchored_share", "ANCHORED share", 3),
          ("regain_anchored_s", "regain ANCHORED (s)", 1), ("detection_delay_s", "detection delay (s)", 1),
          ("blocks_to_detection", "detection (blocks)", 1), ("time_to_sovereign_s", "to SOVEREIGN (s)", 1)]


def cell(vals, nd):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    lo, hi = min(vals), max(vals)
    return f"{st.mean(vals):.{nd}f} ({lo:.{nd}f}--{hi:.{nd}f})" if len(vals) > 1 else f"{vals[0]:.{nd}f}"


def main():
    runs = defaultdict(list)
    for f in sorted(glob.glob(os.path.join(SRC, "nonstationary_*_o*_t*_*.json"))):
        m = re.match(r"nonstationary_(.+)_o(\d+)_t(\d+)_", os.path.basename(f))
        runs[(m.group(1), int(m.group(2)))].append(json.load(open(f)))
    offsets = sorted({o for _, o in runs})
    lines = ["# Live three-phase hysteresis runs (mean and range over trials; fresh genesis per run)", ""]
    for off in offsets:
        lines += [f"## Offset {off} s (healthy in ANCHORED before the outage)", "",
                  "| config | runs | " + " | ".join(h for _, h, _ in FIELDS) + " | left ANCHORED during offset | recovered |",
                  "|---|---|" + "---|" * (len(FIELDS) + 2)]
        for cfg in ORDER:
            rs = runs.get((cfg, off), [])
            if not rs:
                continue
            row = [cell([r.get(k) for r in rs], nd) for k, _, nd in FIELDS]
            left = sum(bool(r.get("left_anchored_during_offset")) for r in rs)
            rec = sum(bool(r.get("recovered")) for r in rs)
            lines.append(f"| {cfg} | {len(rs)} | " + " | ".join(row) + f" | {left}/{len(rs)} | {rec}/{len(rs)} |")
        lines.append("")
    # quiet-phase share before the noise (first quiet phase), pooled over offsets
    lines += ["## ANCHORED share of the first quiet phase (no injected noise), pooled over offsets", "",
              "| config | runs | share (mean, range) |", "|---|---|---|"]
    for cfg in ORDER:
        rs = [r for (c, _), v in runs.items() if c == cfg for r in v]
        if rs:
            lines.append(f"| {cfg} | {len(rs)} | {cell([r.get('quiet1_anchored_share') for r in rs], 2)} |")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    write_tex(runs)


NAMES = {"static2": "Static $k{=}2$", "static4": "Static $k{=}4$", "adaptiveW16": "Adaptive, window 16",
         "adaptiveW64": "Adaptive, window 64", "adaptiveW128": "Adaptive, window 128",
         "adaptiveK4W64": "Adaptive, cap 4, window 64"}


def write_tex(runs):
    """Paper table: noisy phase and detection after the noise, offsets 0 and 60 s."""
    rows = []
    for cfg in ORDER:
        r0, r60 = runs.get((cfg, 0), []), runs.get((cfg, 60), [])
        allr = r0 + r60
        d60 = [r["detection_delay_s"] for r in r60 if r.get("detection_delay_s") is not None]
        left = sum(bool(r.get("left_anchored_during_offset")) for r in r60)
        if d60:
            c60 = cell(d60, 1) + (f" [{left}/{len(r60)} left \\textsc{{Anchored}}]" if left else "")
        else:
            c60 = f"none: left \\textsc{{Anchored}} in {left}/{len(r60)}"
        rows.append(f"{NAMES[cfg]} & {cell([r['noisy_flaps'] for r in allr], 1)} & {cell([r['noisy_anchored_share'] for r in allr], 2)} & "
                    f"{cell([r['detection_delay_s'] for r in r0], 1)} & {cell([r['time_to_sovereign_s'] for r in r0], 1)} & {c60} \\\\")
    tex = ("% Generated by scripts/e5_hysteresis_flapping/summarize_live_nonstationary.py -- do not edit.\n"
           "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
           " & \\textbf{Flaps} & \\textbf{\\textsc{Anchored} share} & \\textbf{Detection, offset 0} & \\textbf{To \\textsc{Sovereign}, offset 0} & \\textbf{Detection, offset 60} \\\\\n"
           " & & noisy phase & s & s & s \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    with open(TEX, "w") as f:
        f.write(tex)


if __name__ == "__main__":
    main()
