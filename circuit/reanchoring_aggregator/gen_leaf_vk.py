#!/usr/bin/env python3
# Emits src/leaf_vk.nr (LEAF_VK + LEAF_KEY_HASH as compile-time constants) from
# a `bb write_vk -t noir-recursive` output dir of circuit/reanchoring.
# Constants, not witnesses: a witness VK would let a prover swap in another circuit.
import sys

d = sys.argv[1]
def fields(p):
    b = open(p, "rb").read()
    assert len(b) % 32 == 0
    return [int.from_bytes(b[i:i + 32], "big") for i in range(0, len(b), 32)]

vk = fields(f"{d}/vk")
kh = fields(f"{d}/vk_hash")
assert len(kh) == 1
body = ",\n".join(f"    {v}" for v in vk)
print(f"""// Generated by gen_leaf_vk.py from circuit/reanchoring -- do not edit.
use bb_proof_verification::UltraHonkVerificationKey;

pub global LEAF_VK: UltraHonkVerificationKey = [
{body},
];
pub global LEAF_KEY_HASH: Field = {kh[0]};""")
